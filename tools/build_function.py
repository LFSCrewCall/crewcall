"""Build supabase/functions/crewcall/index.ts from tools/crewcall-function.ts.
Copies in the two email designs (emails/*.js) and the default lists from data.js,
so the server and the app always use the same designs. Run: python3 tools/build_function.py"""
import os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, 'tools', 'crewcall-function.ts'), encoding='utf-8').read()
dig = open(os.path.join(root, 'emails', 'digest-template.js'), encoding='utf-8').read()
nl = open(os.path.join(root, 'emails', 'newsletter-template.js'), encoding='utf-8').read()
data = open(os.path.join(root, 'data.js'), encoding='utf-8').read()
# run data.js in node and keep window.CC_CONST as JSON (plain data, no functions)
import subprocess
const = subprocess.check_output(['node', '-e',
    'global.window={};global.location={search:"",hash:""};' +
    'try{require(process.argv[1])}catch(e){}' +
    'if(!window.CC_CONST)throw new Error("CC_CONST missing");' +
    'process.stdout.write(JSON.stringify(window.CC_CONST))', os.path.join(root, 'data.js')]).decode()
out = src.replace('/*@@DIGEST@@*/', '// @ts-nocheck: emails/digest-template.js\n' + dig.strip()) \
         .replace('/*@@NEWSLETTER@@*/', '// emails/newsletter-template.js\n' + nl.strip()) \
         .replace('/*@@CONST@@*/', const)
out = '// @ts-nocheck\n// GENERATED by tools/build_function.py from tools/crewcall-function.ts. Edit that file, not this one.\n' + out
dst = os.path.join(root, 'supabase', 'functions', 'crewcall', 'index.ts')
os.makedirs(os.path.dirname(dst), exist_ok=True)
open(dst, 'w', encoding='utf-8').write(out)
print('wrote', dst, len(out), 'bytes')
